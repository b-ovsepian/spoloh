//go:build ignore

// ukrainealarm_gen.go regenerates ukrainealarm_table.go — the map from a
// published alerts.in.ua location UID onto ukrainealarm.com's own id for the
// same place.
//
//	go run ukrainealarm_gen.go -key <the key mailed to you after registering>
//	go run ukrainealarm_gen.go -json regions.json   # from a saved response
//
// # Why it is run by hand, and not by "go generate"
//
// GET /api/v3/regions is the authority for these ids and it is behind the
// same credential everything else on that API is. The key belongs to whoever
// registered for it, it is not in this repository and must never be committed
// to it, so this cannot run unattended the way locations_gen.go can. Run it
// once, read the diff, commit the table. Nothing here prints the key.
//
// # Why a committed table and not a lookup at runtime
//
// The reason locations_gen.go gives: a device is commissioned on a workbench
// with no internet, off a phone hotspot, or on a LAN nobody has given a route
// yet, and the mapping has to be there before the first poll succeeds. A
// committed table is also the only review this mapping will ever get — a
// person reading a diff.
//
// # Where the actual matching lives
//
// In MatchUkraineAlarmRegions, in the package beside this file, because a
// generator behind a //go:build ignore tag cannot be tested and the rule it
// implements — refuse on any ambiguity, emit nothing for a place with no
// counterpart — is the one rule here whose failure is a device announcing for
// somewhere else. This file is the part that cannot be tested anyway: a
// flag, an HTTP request, and a file write.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"time"

	"github.com/b-ovsepian/spoloh/internal/alertsource"
)

// regionsURL is the authority for these ids.
const regionsURL = "https://api.ukrainealarm.com/api/v3/regions"

func main() {
	key := flag.String("key", "", "ukrainealarm.com API key (required unless -json is given)")
	from := flag.String("json", "", "read the regions tree from this file instead of fetching it")
	out := flag.String("out", "ukrainealarm_table.go", "file to write")
	flag.Parse()

	data, err := load(*from, *key)
	if err != nil {
		log.Fatal(err)
	}
	var body struct {
		States []alertsource.UkraineAlarmRegionView `json:"states"`
	}
	if err := json.Unmarshal(data, &body); err != nil {
		log.Fatalf("parse the regions tree: %v", err)
	}
	if len(body.States) == 0 {
		log.Fatal("the regions tree carries no states; this is not the response the client was written against")
	}

	mappings, err := alertsource.MatchUkraineAlarmRegions(body.States)
	if err != nil {
		log.Fatal(err)
	}
	src, err := emit(mappings)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s: %d of %d published locations mapped",
		*out, len(mappings), len(alertsource.Locations()))
}

func load(path, key string) ([]byte, error) {
	if path != "" {
		return os.ReadFile(path)
	}
	if key == "" {
		return nil, fmt.Errorf("-key is required: GET %s answers 401 without one", regionsURL)
	}
	req, err := http.NewRequest(http.MethodGet, regionsURL, nil)
	if err != nil {
		return nil, err
	}
	// Bare, with no scheme prefix: the spec declares an apiKey in a header
	// that happens to be called Authorization, not an HTTP authentication
	// scheme. "Bearer " in front of it earns a 401 that reads like a bad key.
	req.Header.Set("Authorization", key)
	req.Header.Set("Accept", "application/json")

	hc := &http.Client{Timeout: 60 * time.Second}
	resp, err := hc.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		// The key is never in this message. It is a credential, and a
		// generator's output is a thing people paste into issues.
		return nil, fmt.Errorf("fetch %s: http %d", regionsURL, resp.StatusCode)
	}
	return io.ReadAll(resp.Body)
}

func emit(ms []alertsource.UkraineAlarmMapping) ([]byte, error) {
	sort.Slice(ms, func(i, j int) bool { return ms[i].UID < ms[j].UID })

	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by ukrainealarm_gen.go; DO NOT EDIT.
//
// Source: %s
// Generated: %s
//
// Regenerate with "go run ukrainealarm_gen.go -key <your key>" and commit the
// result. Do not hand-edit: the generator carries the checks that keep a place
// attached to the id that names it, and an edit made here goes through none of
// them.

package alertsource

// ukraineAlarmRegions maps a published alerts.in.ua location UID onto
// ukrainealarm.com's own id for the same place. A location with no entry is
// one this source cannot serve; see UkraineAlarmRegionID.
var ukraineAlarmRegions = map[int]string{
`, regionsURL, time.Now().UTC().Format("2006-01-02"))
	for _, m := range ms {
		fmt.Fprintf(&b, "\t%d: %q, // %s\n", m.UID, m.RegionID, m.Name)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
